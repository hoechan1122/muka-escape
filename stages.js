// ============================================================
//  ステージの書き方(このファイルだけ書き換えればOK)
// ============================================================
//  map の中の 1文字 = 1マス。横に長く書くほど長いステージになる。
//  縦は 15行 がちょうど画面の高さ。
//
//  【地形】
//   .    なにもない(空気)
//   #    地面
//   B    偽の壁(見た目は地面と同じ。通り抜けられる)
//   =    レンガ(乗れるブロック)
//   Q    ?ブロック(下から叩くとコイン)
//   M    ?ブロック(見た目は Q と同じ。叩くと死ぬ)
//   N    ?ブロック(見た目は Q と同じ。叩くと踏めない敵 k が出てくる)
//   TT   土管の口(2マスで1本。下に II を続ける)
//   II   土管の胴体(ふつうは入れない。stages.js の warps に書いた土管だけ↓で入れる)
//   o    コイン
//   C    中間地点(触るとセーブ。死んだらここから)
//   J    偽の中間地点(見た目は C と同じ。触ると死ぬ)
//   H    謎の答えの中間地点(見た目は C と同じ。触ると扉が開く。door に flag: true)
//   W    雲(上からだけ乗れる。下からはすり抜ける)
//   Z    消える雲(見た目は W と同じ。乗ってしばらくすると消える)
//
//  【スタートとゴール】
//   P    スタート地点(1ステージに1つ)
//   G    ゴール(トイレ)        U  偽物のトイレ(触ると死ぬ)
//   Y    ゴール(ポール)        F  偽物のポール(触ると死ぬ)
//   O    偽エンディングのポール(触るとクリア画面とスタッフロールが流れて「ウソです」→続きから)
//
//  【罠】
//   ^    トゲ(最初から見える)
//   *    隠しトゲ(近づくと急に生える)
//   ?    見えないブロック(下から頭をぶつけると出てくる)
//   X    落ちる床(見た目は地面と同じ。乗ると落ちる)
//   V    落ちてくるレンガ(見た目はレンガ。下を通ると落ちてくる)
//   v    一気に落ちるレンガ(横につながった v が全部いっぺんに落ちる)
//   L    順番に落ちるレンガ(横につながった L が、近いものから1個ずつ落ちる)
//   h    追いかけてくるレンガ(近づくと外れて、主人公を追いかけてくる)
//   S    ドッスン(ななめ下に突っ込んでくる石。2マスくらいの大きさ)
//   A    ?ブロック(見た目は Q と同じ。叩くと 見えない足場 j が全部レンガになる)
//   j    見えない足場(A を叩くまで何もない)
//
//  【敵】
//   e    敵(ほんとに踏める)
//   k    敵(見た目は e と同じ。踏むと自分が死ぬ)
//   E    おばけ(背中を向けると近づいてくる。見ると止まる)
//   <    逆おばけ(見ているときだけ近づいてくる。背中を向けると止まる)
//   p    パックン(土管 TT のすぐ上の左側に置く。出たり引っこんだりする)
//
//  【謎解き】
//   D    鍵つきの扉(謎が解けると開く)
//   K    ポスト(ここで↓ → 答えを入れる)
//   a b c d  順番ブロック(door.order の順に下から叩くと扉が開く)
//            f g i l m n q r s t u w x y z も使える(door.switches に書いたものだけブロックになる)
//   1〜9 と ! $ % & + @ ~ ;   看板(下の signs に書いた文章が出る)
//
//  注意
//   ・行の先頭にスペースを入れない(マスがずれる)
//   ・map の前後の ` (バッククォート) は消さない
//   ・書き換えたら「保存」→ ブラウザで F5(再読み込み)
// ============================================================

